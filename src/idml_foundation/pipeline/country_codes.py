"""Country name -> ISO 3166-1 alpha-2 (EN/PT/ES), generated from Unicode CLDR.

Source: Unicode CLDR cldr-localenames-full (en, pt, es) territories, Unicode License v3,
plus explicit aliases (USA, EUA, UK, ...).
Keys are accent-free, case-folded, whitespace-collapsed names (see ``country_key``).
"""

import unicodedata


def country_key(name: str) -> str:
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return " ".join(ascii_name.casefold().replace("&", "and").split())


def iso_country_code(name: str | None) -> str | None:
    """ISO alpha-2 code for a country name typed in EN, PT or ES; None when unknown."""
    if not name:
        return None
    return COUNTRY_CODES.get(country_key(name.strip(" .,;")))


